import type { ThemeConfig } from "antd";
import { theme as antdTheme } from "antd";
import type { EmbeddedAppearance } from "@/hooks/use-embedded-appearance";

const neutral = {
    light: {
        primary: "#171717",
        primaryHover: "#000000",
        primaryText: "#ffffff",
        elevatedBg: "#ffffff",
        itemHoverBg: "rgba(23, 23, 23, 0.06)",
        itemSelectedBg: "rgba(23, 23, 23, 0.1)",
        itemSelectedHoverBg: "rgba(23, 23, 23, 0.14)",
        itemText: "#171717",
        tableSelectedBg: "rgba(17, 17, 17, 0.05)",
        tableSelectedHoverBg: "rgba(17, 17, 17, 0.08)",
    },
    dark: {
        primary: "#fafafa",
        primaryHover: "#ffffff",
        primaryText: "#171717",
        elevatedBg: "#1c1917",
        itemHoverBg: "rgba(250, 250, 249, 0.08)",
        itemSelectedBg: "rgba(250, 250, 249, 0.12)",
        itemSelectedHoverBg: "rgba(250, 250, 249, 0.16)",
        itemText: "#fafafa",
        tableSelectedBg: "rgba(255, 255, 255, 0.08)",
        tableSelectedHoverBg: "rgba(255, 255, 255, 0.12)",
    },
};

export function getAntThemeConfig(dark: boolean, appearance: EmbeddedAppearance | null = null): ThemeConfig {
    const defaults = dark ? neutral.dark : neutral.light;
    const host = appearance?.colors;
    const color = {
        ...defaults,
        primary: host?.primary ?? defaults.primary,
        primaryHover: host?.primary ?? defaults.primaryHover,
        primaryText: host?.["primary-foreground"] ?? defaults.primaryText,
        elevatedBg: host?.popover ?? defaults.elevatedBg,
        itemHoverBg: host?.accent ?? defaults.itemHoverBg,
        itemSelectedBg: host?.accent ?? defaults.itemSelectedBg,
        itemSelectedHoverBg: host?.accent ?? defaults.itemSelectedHoverBg,
        itemText: host?.foreground ?? defaults.itemText,
    };

    return {
        algorithm: dark ? antdTheme.darkAlgorithm : antdTheme.defaultAlgorithm,
        cssVar: { key: dark ? "infinite-canvas-dark" : "infinite-canvas-light" },
        token: {
            ...(appearance ? {
                colorBgBase: host?.background,
                colorBgContainer: host?.card,
                colorText: host?.foreground,
                colorTextSecondary: host?.["muted-foreground"],
                colorBorder: host?.border,
                colorBorderSecondary: host?.border,
                fontFamily: appearance.fontFamily,
                fontSize: appearance.fontSize,
                borderRadius: appearance.radius,
                controlHeight: appearance.controlHeight,
            } : {}),
            colorPrimary: color.primary,
            colorInfo: color.primary,
            colorLink: color.primary,
            colorLinkHover: color.primaryHover,
            colorLinkActive: color.primary,
            colorTextLightSolid: color.primaryText,
            colorBgElevated: color.elevatedBg,
            controlItemBgHover: color.itemHoverBg,
            controlItemBgActive: color.itemSelectedBg,
            controlItemBgActiveHover: color.itemSelectedHoverBg,
        },
        components: {
            Button: {
                primaryShadow: "none",
            },
            Dropdown: {
                colorBgElevated: color.elevatedBg,
                colorText: color.itemText,
                controlItemBgHover: color.itemHoverBg,
                controlItemBgActive: color.itemSelectedBg,
                controlItemBgActiveHover: color.itemSelectedHoverBg,
            },
            Menu: {
                popupBg: color.elevatedBg,
                itemActiveBg: color.itemSelectedBg,
                itemHoverBg: color.itemHoverBg,
                itemSelectedBg: color.itemSelectedBg,
                itemSelectedColor: color.itemText,
                darkPopupBg: neutral.dark.elevatedBg,
                darkItemHoverBg: neutral.dark.itemHoverBg,
                darkItemSelectedBg: neutral.dark.itemSelectedBg,
                darkItemSelectedColor: neutral.dark.itemText,
            },
            Select: {
                optionActiveBg: color.itemHoverBg,
                optionSelectedBg: color.itemSelectedBg,
                optionSelectedColor: color.itemText,
            },
            Table: {
                rowSelectedBg: color.tableSelectedBg,
                rowSelectedHoverBg: color.tableSelectedHoverBg,
            },
        },
    };
}
